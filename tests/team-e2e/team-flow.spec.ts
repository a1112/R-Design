  await capture.close();expect(bounds).not.toBeNull();
  await page.getByRole('button',{name:'刷新工作空间',exact:true}).click();
  await page.getByText('版本比较验收',{exact:true}).first().click();
  await page.getByTestId('team-upload-version').click();
  const exported={schemaVersion:1,project:{name:'首页 V2',snapshots:[{id:'snapshot-v2',kind:'snapshot',status:'frozen',image:'data:image/png;base64,'+secondImage.toString('base64'),width:800,height:600,nodes:[{runtimeNodeId:'primary-button',tag:'button',text:'立即开始监控',bounds:{x:bounds!.x,y:bounds!.y,w:bounds!.width,h:bounds!.height}}]}]},changes:[]};
