import { test, expect, type Page } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import path from 'node:path';

const ownerEmail = 'owner@rdesign.test';
const ownerPassword = 'Isolated-E2E-Owner-Only-2026';
const reviewerEmail = 'reviewer@rdesign.test';
const reviewerPassword = 'Isolated-E2E-Reviewer-Only-2026';
const prefix = (process.env.RDESIGN_TEAM_E2E_BASE_PATH ?? '').replace(/\/$/, '');
const apiBase = `${prefix}/api/team`;
async function login(page:Page, email:string, password:string) {
  await page.goto(`${prefix}/team`);
  await page.getByTestId('team-login-email').fill(email);
  await page.getByTestId('team-login-password').fill(password);
  await page.getByTestId('team-login-submit').click();
  await expect(page.getByTestId('team-create-project')).toBeVisible();
}
